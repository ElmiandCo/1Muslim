/** Run: node scripts/game-flight-pose-smoke.mjs (uses the real TypeScript pose helper). */
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
import ts from "typescript";
const source=readFileSync(new URL("../app/components/gameFlightPose.ts",import.meta.url),"utf8");
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};
vm.runInNewContext("(function(module,exports){"+js+"})")(mod,mod.exports);
const pose=mod.exports.calculateGameFlightPose;
const base={flying:true,verticalSpeed:0,groundClearance:10,takeoffAgeMs:1000,landingAgeMs:1000,forwardInput:false};
const cruise=pose(base),up=pose({...base,verticalSpeed:9}),down=pose({...base,verticalSpeed:-12});
assert.equal(cruise.phase,"cruise");
assert.equal(up.phase,"ascending");
assert.equal(down.phase,"descending");
assert.ok(up.armLift>cruise.armLift);
assert.ok(down.armLift<cruise.armLift);
assert.ok(up.trailSlope>0&&down.trailSlope<0);
assert.ok(down.legLift>cruise.legLift);
assert.equal(pose({...base,takeoffAgeMs:200}).phase,"takeoff");
assert.ok(pose({...base,takeoffAgeMs:200}).torsoLean<cruise.torsoLean);
assert.equal(pose({...base,flying:false,verticalSpeed:-15,groundClearance:250}).phase,"falling");
assert.ok(pose({...base,flying:false,verticalSpeed:-15,groundClearance:250}).armLift>0);
assert.equal(pose({...base,flying:false,verticalSpeed:0,groundClearance:0,landingAgeMs:100}).phase,"landing");
assert.equal(pose({...base,flying:false,verticalSpeed:0,groundClearance:0,landingAgeMs:1000}).phase,"grounded");
assert.equal(pose({...base,flying:false,verticalSpeed:-15,groundClearance:0}).phase,"grounded");
assert.ok(pose({...base,forwardInput:true}).torsoLean>cruise.torsoLean);
assert.equal(pose({...base,groundClearance:100000,verticalSpeed:0}).phase,"cruise");
console.log("PASS: 16 deterministic game flight pose assertions");
